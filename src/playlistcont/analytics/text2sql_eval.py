def demo_store():
    """Build the deterministic seed-7 demo store the fingerprints are pinned to."""
    from ..history.store import HistoryStore
    from ..history.synthetic import make_synthetic_history

    return HistoryStore.from_history(make_synthetic_history(seed=7, n_days=730))


def _candidate_sql(q: EvalQuestion, sql_source: Union[str, Callable[[str], str]]) -> Optional[str]:
    """Resolve the candidate SQL for a question under a given source, or None to skip."""
    if callable(sql_source):
        return T.nl_to_sql(q.question, sql_source)
    if sql_source == "gold":
        return q.gold_sql
    if sql_source == "templates":
        if q.template_id is None:
            return None  # not template-answerable; excluded from the templates subset
        return T.TEMPLATES_BY_ID[q.template_id].build()
    raise ValueError(f"unknown sql_source {sql_source!r}")


def run_eval(
    store,
    sql_source: Union[str, Callable[[str], str]] = "gold",
    questions: Optional[List[EvalQuestion]] = None,
) -> dict:
    """Execution-accuracy of ``sql_source`` over the gold set against ``store``.

    Returns ``{"accuracy": float, "n": int, "passed": int, "details": [...]}`` where each
    detail is ``{"id", "ok", "expected", "got", "error"}``.  Questions the source cannot
    answer (e.g. LLM-only questions when ``sql_source="templates"``) are excluded from
    the denominator, not counted as failures.
    """
    qs = questions if questions is not None else EVAL_QUESTIONS
    details: List[dict] = []
    considered = 0
    passed = 0
    for q in qs:
        sql = _candidate_sql(q, sql_source)
        if sql is None:
            continue
        considered += 1
        expected = EXPECTED_FINGERPRINTS.get(q.id)
        try:
            df = store.query(sql)
            got = T.result_fingerprint(df)
            ok = got == expected
            details.append({"id": q.id, "ok": ok, "expected": expected, "got": got, "error": None})
        except Exception as exc:  # a candidate that fails to run is a miss, not a crash
            ok = False
            details.append({"id": q.id, "ok": False, "expected": expected,
                            "got": None, "error": str(exc)})
        if ok:
            passed += 1
    accuracy = passed / considered if considered else 0.0
    return {"accuracy": accuracy, "n": considered, "passed": passed, "details": details}


def compute_fingerprints(store) -> Dict[str, Tuple[int, str]]:
    """Fingerprint every gold SQL against ``store`` (used to (re)generate the constants)."""
    out: Dict[str, Tuple[int, str]] = {}
    for q in EVAL_QUESTIONS:
        out[q.id] = T.result_fingerprint(store.query(q.gold_sql))
    return out


def _render_constants(fps: Dict[str, Tuple[int, str]]) -> str:
    lines = ["EXPECTED_FINGERPRINTS: Dict[str, Tuple[int, str]] = {"]
    for q in EVAL_QUESTIONS:
        n, h = fps[q.id]
        lines.append(f'    "{q.id}": ({n}, "{h}"),')
    lines.append("}")
    return "\n".join(lines)


