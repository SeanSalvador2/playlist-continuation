"""A gold NL->SQL evaluation set over the deterministic seed-7 demo history.

40 natural-language questions, each with a hand-written **gold SQL** answer and an
**expected-result fingerprint** computed once against the seed-7 demo store
(``make_synthetic_history(seed=7, n_days=730)``).  The fingerprint is
``(row_count, sha256-of-sorted-first-column-values)`` — see
:func:`playlistcont.analytics.text2sql.result_fingerprint` — so it is invariant to row
order but pinned to the actual returned set, and stable across DuckDB versions because
it hashes rendered *values*, not engine internals.

:func:`run_eval` measures **execution accuracy**: a candidate SQL "passes" a question
when the fingerprint of its result equals the stored expected fingerprint.  The candidate
SQL comes from a chosen ``sql_source``:

* ``"gold"`` — the gold SQL itself (a determinism sanity check; should be 100%).
* ``"templates"`` — for the questions backed by a :mod:`~playlistcont.analytics.text2sql`
  template, the SQL the template builds at its default slots.  These MUST score 100%
  (asserted in the tests): the templates are the keyless engine behind these questions.
* a callable ``llm_fn`` — the natural-language path
  (:func:`playlistcont.analytics.text2sql.nl_to_sql`); each question's SQL is generated
  from the model and scored.  (No model ships here; this is the harness the future LLM
  wiring is evaluated with.)

Questions carry ``template_id`` when a template answers them (20 of 40) and ``None`` for
the LLM-only long tail (the remaining 20).  ``EXPECTED_FINGERPRINTS`` is regenerated by
running this module as a script: ``python -m playlistcont.analytics.text2sql_eval``.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Dict, List, Optional, Tuple, Union

from . import text2sql as T


@dataclass(frozen=True)
class EvalQuestion:
    """One gold NL->SQL item."""

    id: str
    question: str
    gold_sql: str
    template_id: Optional[str] = None  # set when a keyless template answers this


def _tmpl_sql(template_id: str) -> str:
    """The SQL a template builds at its default slots (its gold answer)."""
    return T.TEMPLATES_BY_ID[template_id].build()


